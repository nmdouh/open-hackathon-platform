const LANGS = { en, ar };
const KEY = 'ohp.lang';
let current = 'en';
try {
  const saved = localStorage.getItem(KEY);
  if (saved && LANGS[saved]) current = saved;
  else if ((navigator.language || '').toLowerCase().startsWith('ar')) current = 'ar';
} catch { /* storage unavailable */ }

export const lang = () => current;
export function setLang(l) {
  if (!LANGS[l]) return;
  current = l;
  try { localStorage.setItem(KEY, l); } catch { /* ignore */ }
}
export function hasStoredLang() {
  try { return Boolean(localStorage.getItem(KEY)); } catch { return false; }
}

export function t(key, vars) {
  let s = LANGS[current][key] ?? en[key];
  if (s === undefined) return key;
  if (Array.isArray(s)) s = s.join(' ');
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s;
}
export function tList(key) {
  const v = LANGS[current][key] ?? en[key];
  return Array.isArray(v) ? v : [];
}

export function errorText(err) {
  if (!err) return errors[current].INTERNAL;
  const code = err.code || 'INTERNAL';
  let msg = errors[current][code];
  if (!msg && /_NOT_FOUND$/.test(code)) msg = errors[current].NOT_FOUND;
  if (!msg) msg = errors[current].REQUEST_FAILED;
  if (code === 'VALIDATION_FAILED' && Array.isArray(err.details) && err.details.length) {
    msg += ` (${err.details.map((d) => d.path || d).join(', ')})`;
  }
  return msg;
}

export const dictionaries = LANGS;
